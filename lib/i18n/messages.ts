export const MESSAGES:Record<Locale,Messages>={en,hi,ar,ur};

export type Translate=(key:MessageKey,vars?:Record<string,string|number>)=>string;

/** Turns an API error response into a message in the visitor's language, falling back to the server's English text. */
export function apiError(t:Translate,status:number,data:{error?:string;code?:string;retryAfterSeconds?:number}){
  if(status===429)return t("err.rate_limited",{minutes:Math.max(1,Math.ceil((data.retryAfterSeconds||60)/60))});
  const key=("err."+data.code) as MessageKey;
  return data.code&&key in en?t(key):data.error||t("auth.failed");
}

export function translator(locale:Locale):Translate{
  const dict=MESSAGES[locale]||en;
  return (key,vars)=>{
    let text=dict[key]??en[key]??key;
    if(vars)for(const [name,value] of Object.entries(vars))text=text.replaceAll("{"+name+"}",String(value));
    return text;
  };
}
